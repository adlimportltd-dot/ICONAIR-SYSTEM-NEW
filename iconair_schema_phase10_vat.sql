-- ---------------------------------------------------------------------
--  טיוטת סכימה — שלב 10: מצב מע"מ פרטני לכל לקוח (כולל / לא כולל).
--
--  ⚠ הצעה בלבד. לא רץ מעולם. דורש ששלב 9 (billing) כבר רץ.
--
--  ברירת המחדל היא 'included' (כולל מע"מ) בכוונה, לא 'excluded':
--  amount_due כבר קיים משלב 9 ותואר שם כ"סה"כ לתשלום" — כלומר לקוחות
--  קיימים כבר הוזנו איתו כסכום סופי. אם ברירת המחדל הייתה 'excluded'
--  (לא כולל), כל amount_due קיים היה מתפרש פתאום כמחיר לפני מע"מ,
--  והסכום הסופי המחושב היה קופץ ב-18% בלי שאף אחד שינה כלום. 'included'
--  שומר על המשמעות המקורית של הנתונים הקיימים בדיוק כפי שהם.
--
--  18% הוא קבוע בקוד (VAT_RATE ב-mappers.js), לא עמודה בטבלה — זה
--  שיעור המע"מ הארצי, לא הגדרה פר-לקוח. אם זה אי פעם ישתנה (כמו
--  שקרה בעבר בישראל), זה שינוי קוד חד-פעמי, לא נתון שצריך DB.
-- ---------------------------------------------------------------------

do $$ begin
  create type public.vat_mode as enum ('included', 'excluded');
exception when duplicate_object then null; end $$;

alter table public.customers
  add column if not exists vat_mode public.vat_mode not null default 'included';
